-- ROLES --
-- Salen de los legajos, como en el alta del backend. El NOT EXISTS saltea los que ya están (el
-- admin del script de la base ya tiene el suyo).
INSERT INTO usuario_rol (usuario_id, rol_id)
SELECT u.id, r.id
FROM usuario u
JOIN persona p ON p.id = u.persona_id
JOIN rol r ON (r.nombre = 'ROLE_ADMIN'      AND p.legajo_admin      IS NOT NULL)
           OR (r.nombre = 'ROLE_DOCENTE'    AND p.legajo_docente    IS NOT NULL)
           OR (r.nombre = 'ROLE_ESTUDIANTE' AND p.legajo_estudiante IS NOT NULL)
WHERE NOT EXISTS (SELECT 1 FROM usuario_rol ur WHERE ur.usuario_id = u.id AND ur.rol_id = r.id);

-- Resumen: inscripciones de cada carrera por estado, y usuarios de cada rol
SELECT c.id AS carrera_id, c.nombre AS carrera,
       SUM(ic.estado = 'ACTIVA') AS activas, SUM(ic.estado = 'EGRESADO') AS egresados,
       SUM(ic.estado = 'BAJA') AS bajas
FROM carrera c
JOIN plan_estudio p ON p.carrera_id = c.id
JOIN inscripcion_carrera ic ON ic.plan_estudio_id = p.id
GROUP BY c.id, c.nombre
ORDER BY c.id;

SELECT r.nombre AS rol, COUNT(*) AS usuarios
FROM usuario_rol ur
JOIN rol r ON r.id = ur.rol_id
GROUP BY r.id, r.nombre
ORDER BY r.id;
